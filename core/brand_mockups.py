"""Branding MOCKUPS, drawn entirely in code (2026-11-15, docs/BRANDING.md).

A brand concept (palette, font pair, logo mark, a few lines of copy — see
core/branding.clean_concept) goes in; one HTML page of inline SVG mockups
comes out: logo, business card, shop sign, flyer, poster and how a website
could look.

THE RULE: every letter and every logo on a mockup is composed HERE, as SVG
text and shapes. Nothing is generated by an image model — image models still
fail at text, and a mockup with a misspelt business name is worse than none.
So this module has no network call, no model call and no file storage: the
page is rebuilt from the stored concept on every view.

The page is served with `page_headers()`: a CSP sandbox without
allow-same-origin and no script source at all, so even a concept that
somehow carried markup could not reach the dashboard's session. Every value
is XML-escaped on the way in regardless.
"""
import html
import re

ITEMS = ("logo", "business_card", "signage", "flyer", "poster", "website")
MARKS = ("circle", "square", "arch", "leaf", "drop", "hex", "spark", "wave", "ring", "diamond")
LAYOUTS = ("stacked", "inline", "badge")

# Curated pairs only: each family exists on Google Fonts with Hebrew. Rubik
# (Cyrillic) and Cairo (Arabic) ride in every stack so no script falls back to
# a system serif.
FONTS = {
    "heebo": "Heebo", "rubik": "Rubik", "assistant": "Assistant", "alef": "Alef",
    "secular": "Secular One", "suez": "Suez One", "frank": "Frank Ruhl Libre", "varela": "Varela Round",
}
_FONT_QUERY = ("family=Heebo:wght@400;700;900&family=Rubik:wght@400;700;900&family=Assistant:wght@400;700"
               "&family=Alef:wght@400;700&family=Secular+One&family=Suez+One&family=Frank+Ruhl+Libre:wght@400;700;900"
               "&family=Varela+Round&family=Cairo:wght@400;700;900&display=swap")
FONT_CSS_URL = "https://fonts.googleapis.com/css2?" + _FONT_QUERY

_HEX = re.compile(r"^#[0-9a-fA-F]{6}$")
RTL_LANGS = ("he", "ar")


def page_headers() -> dict:
    csp = "; ".join([
        "sandbox", "default-src 'none'", "style-src 'unsafe-inline' https://fonts.googleapis.com",
        "font-src https://fonts.gstatic.com", "img-src data:", "base-uri 'none'", "form-action 'none'",
        "object-src 'none'", "frame-ancestors 'none'"])
    return {"Cache-Control": "no-store", "Content-Security-Policy": csp, "X-Content-Type-Options": "nosniff",
            "X-Robots-Tag": "noindex", "Referrer-Policy": "no-referrer"}


# ─── Colour helpers ──────────────────────────────────────────────────────────

def _rgb(color: str) -> tuple:
    return tuple(int(color[i:i + 2], 16) for i in (1, 3, 5))


def luminance(color: str) -> float:
    def channel(v):
        v = v / 255
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (channel(v) for v in _rgb(color))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a: str, b: str) -> float:
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def readable_on(background: str, preferred: str = "") -> str:
    """A text colour that can be read on `background`: the preferred one when
    it has enough contrast, else near-black or white."""
    if preferred and _HEX.match(preferred) and contrast(preferred, background) >= 4.5:
        return preferred
    return "#111111" if luminance(background) > 0.4 else "#FFFFFF"


def is_hex(value) -> bool:
    return bool(_HEX.match(str(value or "")))


# ─── SVG helpers ─────────────────────────────────────────────────────────────

def _e(value) -> str:
    return html.escape(str(value or ""), quote=True)


def _stack(key: str) -> str:
    return f"'{FONTS.get(key, 'Heebo')}','Rubik','Cairo',sans-serif"


def wrap(text: str, width: int, lines: int) -> list:
    """Greedy word wrap by character count; the last line is cut with an
    ellipsis rather than overflowing the mockup."""
    words, out, line = str(text or "").split(), [], ""
    for word in words:
        if len(line) + len(word) + (1 if line else 0) <= width:
            line = f"{line} {word}".strip()
            continue
        if line:
            out.append(line)
        line = word[:width]
        if len(out) == lines:
            break
    if line and len(out) < lines:
        out.append(line)
    if len(out) == lines and len(" ".join(out)) < len(" ".join(words)):
        out[-1] = out[-1][:max(1, width - 1)].rstrip() + "…"
    return out


def _text(x, y, text, size, fill, font, weight=400, anchor="middle", rtl=False, spacing=0) -> str:
    # `anchor` is PHYSICAL here: "start" = the text's left edge sits at x, "end"
    # = its right edge. Under direction=rtl SVG reverses the two, so swap.
    if rtl and anchor in ("start", "end"):
        anchor = "end" if anchor == "start" else "start"
    # always explicit: the page itself may be dir=rtl, and an inherited
    # direction would flip the anchor of a left-to-right line (a phone number)
    extra = ' direction="rtl" unicode-bidi="plaintext"' if rtl else ' direction="ltr"'
    letter = f' letter-spacing="{spacing}"' if spacing else ""
    return (f'<text x="{x}" y="{y}" font-family="{_stack(font)}" font-size="{size}" font-weight="{weight}" '
            f'fill="{fill}" text-anchor="{anchor}"{letter}{extra}>{_e(text)}</text>')


def _lines(x, y, lines, size, fill, font, weight=400, anchor="middle", rtl=False, gap=1.3) -> str:
    return "".join(_text(x, round(y + i * size * gap, 1), line, size, fill, font, weight, anchor, rtl)
                   for i, line in enumerate(lines))


def _initial(name: str) -> str:
    for ch in str(name or ""):
        if ch.isalpha():
            return ch.upper()
    return "•"


def mark(shape: str, cx: float, cy: float, size: float, main: str, second: str, on_main: str, initial: str,
         font: str) -> str:
    """The logo mark: one of a small set of clean shapes, optionally carrying
    the business's first letter. Centre (cx, cy), fits a size × size box."""
    r = size / 2
    letter = _text(cx, round(cy + size * 0.17, 1), initial, round(size * 0.5, 1), on_main, font, 900)
    if shape == "square":
        return (f'<rect x="{cx - r}" y="{cy - r}" width="{size}" height="{size}" rx="{round(size * 0.22, 1)}" '
                f'fill="{main}"/>{letter}')
    if shape == "hex":
        pts = " ".join(f"{round(cx + r * c, 1)},{round(cy + r * s, 1)}" for c, s in
                       ((0, -1), (0.87, -0.5), (0.87, 0.5), (0, 1), (-0.87, 0.5), (-0.87, -0.5)))
        return f'<polygon points="{pts}" fill="{main}"/>{letter}'
    if shape == "diamond":
        pts = f"{cx},{cy - r} {cx + r},{cy} {cx},{cy + r} {cx - r},{cy}"
        return f'<polygon points="{pts}" fill="{main}"/>{letter}'
    if shape == "ring":
        return (f'<circle cx="{cx}" cy="{cy}" r="{round(r * 0.86, 1)}" fill="none" stroke="{main}" '
                f'stroke-width="{round(size * 0.1, 1)}"/>'
                f'<circle cx="{round(cx + r * 0.62, 1)}" cy="{round(cy - r * 0.62, 1)}" r="{round(size * 0.09, 1)}" '
                f'fill="{second}"/>'
                + _text(cx, round(cy + size * 0.16, 1), initial, round(size * 0.46, 1), main, font, 900))
    if shape == "arch":
        return (f'<path d="M{cx - r},{cy + r} V{cy} A{r},{r} 0 0 1 {cx + r},{cy} V{cy + r} Z" fill="{main}"/>'
                f'<path d="M{cx - r * 0.45},{cy + r} V{cy + r * 0.15} A{r * 0.45},{r * 0.45} 0 0 1 '
                f'{cx + r * 0.45},{cy + r * 0.15} V{cy + r} Z" fill="{second}"/>')
    if shape == "leaf":
        return (f'<path d="M{cx - r},{cy + r} C{cx - r},{cy - r * 0.6} {cx + r * 0.2},{cy - r} {cx + r},{cy - r} '
                f'C{cx + r},{cy + r * 0.2} {cx + r * 0.6},{cy + r} {cx - r},{cy + r} Z" fill="{main}"/>'
                f'<path d="M{cx - r * 0.8},{cy + r * 0.8} L{cx + r * 0.55},{cy - r * 0.55}" stroke="{second}" '
                f'stroke-width="{round(size * 0.06, 1)}" stroke-linecap="round"/>')
    if shape == "drop":
        return (f'<path d="M{cx},{cy - r} C{cx + r * 1.1},{cy + r * 0.1} {cx + r * 0.7},{cy + r} {cx},{cy + r} '
                f'C{cx - r * 0.7},{cy + r} {cx - r * 1.1},{cy + r * 0.1} {cx},{cy - r} Z" fill="{main}"/>'
                f'<circle cx="{round(cx - r * 0.2, 1)}" cy="{round(cy + r * 0.35, 1)}" r="{round(size * 0.1, 1)}" '
                f'fill="{second}"/>')
    if shape == "spark":
        k = r * 0.24
        return (f'<path d="M{cx},{cy - r} L{cx + k},{cy - k} L{cx + r},{cy} L{cx + k},{cy + k} L{cx},{cy + r} '
                f'L{cx - k},{cy + k} L{cx - r},{cy} L{cx - k},{cy - k} Z" fill="{main}"/>'
                f'<circle cx="{round(cx + r * 0.7, 1)}" cy="{round(cy - r * 0.7, 1)}" r="{round(size * 0.07, 1)}" '
                f'fill="{second}"/>')
    if shape == "wave":
        w = round(size * 0.11, 1)
        def one(dy, color):
            y = round(cy + dy, 1)
            return (f'<path d="M{cx - r},{y} Q{cx - r * 0.5},{y - r * 0.5} {cx},{y} T{cx + r},{y}" fill="none" '
                    f'stroke="{color}" stroke-width="{w}" stroke-linecap="round"/>')
        return one(-r * 0.4, main) + one(0, second) + one(r * 0.4, main)
    return f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{main}"/>{letter}'


def _svg(width: int, height: int, body: str, label: str) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" role="img" '
            f'aria-label="{_e(label)}" preserveAspectRatio="xMidYMid meet">{body}</svg>')


class _Look:
    """The concept, resolved once into the colours and fonts each mockup uses."""

    def __init__(self, concept: dict, lang: str):
        palette = concept.get("palette") or {}
        self.ink = palette.get("ink") if is_hex(palette.get("ink")) else "#1B1B1F"
        self.paper = palette.get("paper") if is_hex(palette.get("paper")) else "#FAF7F2"
        self.accent = palette.get("accent") if is_hex(palette.get("accent")) else "#C2552D"
        self.second = palette.get("secondary") if is_hex(palette.get("secondary")) else "#E9C46A"
        self.on_paper = readable_on(self.paper, self.ink)
        self.on_accent = readable_on(self.accent, self.paper)
        self.on_ink = readable_on(self.ink, self.paper)
        self.accent_on_paper = self.accent if contrast(self.accent, self.paper) >= 3 else self.on_paper
        fonts = concept.get("fonts") or {}
        self.display = fonts.get("display") if fonts.get("display") in FONTS else "heebo"
        self.body = fonts.get("text") if fonts.get("text") in FONTS else "assistant"
        logo = concept.get("logo") or {}
        self.shape = logo.get("mark") if logo.get("mark") in MARKS else "circle"
        self.layout = logo.get("layout") if logo.get("layout") in LAYOUTS else "stacked"
        self.name = str(concept.get("name") or "").strip()[:40] or "—"
        self.tagline = str(concept.get("tagline") or "").strip()[:60]
        self.initial = _initial(self.name)
        self.copy = concept.get("copy") or {}
        self.contact = concept.get("contact") or {}
        self.rtl = lang in RTL_LANGS

    def mark(self, cx, cy, size, on_dark=False) -> str:
        main = self.second if on_dark and contrast(self.accent, self.ink) < 2 else self.accent
        return mark(self.shape, cx, cy, size, main, self.second if main != self.second else self.paper,
                    readable_on(main, self.paper), self.initial, self.display)

    def lockup(self, cx, cy, scale, color) -> str:
        """Mark + name (+ tagline) centred on (cx, cy); `scale` 1 ≈ 300 px wide."""
        size = 84 * scale
        name_size = round(min(44, 520 / max(len(self.name), 6)) * scale, 1)
        on_dark = luminance(color) > 0.6
        if self.layout == "inline":
            width = size + 18 * scale + len(self.name) * name_size * 0.56
            left = cx - width / 2
            mark_x = cx + width / 2 - size / 2 if self.rtl else left + size / 2
            text_x = left + (width - size - 18 * scale) / 2 if self.rtl else left + size + 18 * scale + \
                (width - size - 18 * scale) / 2
            out = self.mark(round(mark_x, 1), cy, size, on_dark)
            out += _text(round(text_x, 1), round(cy + name_size * 0.2, 1), self.name, name_size, color,
                         self.display, 900, rtl=self.rtl)
            if self.tagline:
                out += _text(round(text_x, 1), round(cy + name_size * 0.2 + 22 * scale, 1), self.tagline,
                             round(13 * scale, 1), color, self.body, 400, rtl=self.rtl)
            return out
        out = self.mark(cx, round(cy - 34 * scale, 1), size, on_dark)
        if self.layout == "badge":
            out = (f'<circle cx="{cx}" cy="{round(cy - 34 * scale, 1)}" r="{round(size * 0.72, 1)}" fill="none" '
                   f'stroke="{color}" stroke-width="{round(2 * scale, 1)}" stroke-dasharray="2 6"/>') + out
        out += _text(cx, round(cy + 52 * scale, 1), self.name, name_size, color, self.display, 900, rtl=self.rtl)
        if self.tagline:
            out += _text(cx, round(cy + 78 * scale, 1), self.tagline, round(14 * scale, 1), color, self.body,
                         400, rtl=self.rtl, spacing=0 if self.rtl else 1)
        return out


# ─── The six mockups ─────────────────────────────────────────────────────────

def logo_svg(look: _Look) -> str:
    half = 300
    body = (f'<rect width="600" height="340" fill="{look.paper}"/>'
            f'<rect x="{half}" width="{half}" height="340" fill="{look.ink}"/>'
            + look.lockup(150, 165, 0.8, look.on_paper) + look.lockup(450, 165, 0.8, look.on_ink))
    return _svg(600, 340, body, "logo")


def business_card_svg(look: _Look) -> str:
    c = look.contact
    rows = [v for v in (c.get("phone"), c.get("site"), c.get("address")) if v][:3]
    anchor, x = ("end", 548) if look.rtl else ("start", 372)
    back = "".join(_text(x, 196 + i * 26, row, 15, look.on_paper, look.body, 400, anchor) for i, row in
                   enumerate(rows))
    name_anchor_x = 548 if look.rtl else 372
    body = (f'<rect width="640" height="560" fill="#E7E5E1"/>'
            f'<g transform="rotate(-4 320 150)"><rect x="92" y="38" width="456" height="250" rx="14" '
            f'fill="rgba(0,0,0,.18)" transform="translate(6 10)"/>'
            f'<rect x="92" y="38" width="456" height="250" rx="14" fill="{look.ink}"/>'
            + look.lockup(320, 170, 0.78, look.on_ink) + '</g>'
            f'<g transform="rotate(3 320 410)"><rect x="92" y="292" width="456" height="250" rx="14" '
            f'fill="rgba(0,0,0,.18)" transform="translate(6 10)"/>'
            f'<rect x="92" y="292" width="456" height="250" rx="14" fill="{look.paper}"/>'
            f'<rect x="92" y="292" width="14" height="250" fill="{look.accent}"/>'
            + f'<g transform="translate(0 254)">'
            + look.mark(180 if not look.rtl else 180, 162, 70)
            + _text(name_anchor_x, 142, look.name, 24, look.on_paper, look.display, 900, anchor, look.rtl)
            + (_text(name_anchor_x, 166, look.tagline, 13, look.accent_on_paper, look.body, 700, anchor, look.rtl)
               if look.tagline else "")
            + back + '</g></g>')
    return _svg(640, 560, body, "business card")


def signage_svg(look: _Look) -> str:
    wall = "#D9D2C7" if luminance(look.ink) < 0.5 else "#5A5F66"
    body = (f'<rect width="760" height="480" fill="#BFD7E6"/>'
            f'<rect y="60" width="760" height="420" fill="{wall}"/>'
            f'<rect y="430" width="760" height="50" fill="#8D8A85"/>'
            # the sign board
            f'<rect x="80" y="84" width="600" height="120" rx="10" fill="rgba(0,0,0,.22)" transform="translate(0 8)"/>'
            f'<rect x="80" y="84" width="600" height="120" rx="10" fill="{look.ink}"/>'
            + look.mark(140 if not look.rtl else 620, 144, 70, True)
            + _text(400, 156, look.name, round(min(54, 760 / max(len(look.name), 8)), 1), look.on_ink,
                    look.display, 900, rtl=look.rtl)
            + (_text(400, 186, look.tagline, 16, look.on_ink, look.body, 400, rtl=look.rtl) if look.tagline else "")
            # awning
            + "".join(f'<rect x="{80 + i * 50}" y="212" width="50" height="34" '
                      f'fill="{look.accent if i % 2 == 0 else look.paper}"/>' for i in range(12))
            # window and door
            + f'<rect x="100" y="262" width="330" height="168" fill="#F4F1EA" stroke="{look.ink}" stroke-width="6"/>'
            f'<rect x="100" y="262" width="330" height="168" fill="rgba(160,200,225,.35)"/>'
            + look.mark(265, 346, 76)
            + f'<rect x="490" y="262" width="150" height="168" fill="{look.accent}" stroke="{look.ink}" '
            f'stroke-width="6"/><circle cx="{510 if look.rtl else 620}" cy="350" r="6" fill="{look.on_accent}"/>')
    return _svg(760, 480, body, "shop sign")


def flyer_svg(look: _Look) -> str:
    copy = look.copy
    headline = wrap(copy.get("flyer_headline") or look.tagline or look.name, 18, 3)
    para = wrap(copy.get("flyer_body") or "", 38, 4)
    services = [str(s)[:34] for s in (copy.get("services") or []) if s][:3]
    y = 250 + len(headline) * 50
    body = (f'<rect width="520" height="736" fill="{look.paper}"/>'
            f'<rect width="520" height="170" fill="{look.ink}"/>'
            + look.lockup(260, 92, 0.62, look.on_ink)
            + f'<rect x="60" y="208" width="70" height="8" fill="{look.accent}" '
            f'transform="translate({330 if look.rtl else 0} 0)"/>'
            + _lines(260, 268, headline, 40, look.on_paper, look.display, 900, rtl=look.rtl, gap=1.25)
            + _lines(260, y + 14, para, 17, look.on_paper, look.body, 400, rtl=look.rtl, gap=1.5))
    y += 30 + len(para) * 26
    for i, service in enumerate(services):
        yy = y + i * 44
        body += (f'<rect x="80" y="{yy}" width="360" height="34" rx="17" fill="none" stroke="{look.accent_on_paper}" '
                 f'stroke-width="2"/>'
                 + _text(260, yy + 23, service, 16, look.on_paper, look.body, 700, rtl=look.rtl))
    cta = str(copy.get("cta") or "")[:28]
    if cta:
        body += (f'<rect x="130" y="632" width="260" height="56" rx="28" fill="{look.accent}"/>'
                 + _text(260, 668, cta, 21, look.on_accent, look.display, 700, rtl=look.rtl))
    contact = " · ".join(v for v in (look.contact.get("phone"), look.contact.get("site")) if v)
    if contact:
        body += _text(260, 716, contact, 14, look.on_paper, look.body, 400)
    return _svg(520, 736, body, "flyer")


def poster_svg(look: _Look) -> str:
    copy = look.copy
    headline = wrap(copy.get("poster_headline") or copy.get("flyer_headline") or look.name, 12, 3)
    size = 76 if max((len(l) for l in headline), default=1) <= 9 else 60
    body = (f'<rect width="560" height="792" fill="{look.accent}"/>'
            f'<circle cx="280" cy="250" r="230" fill="{look.second}" opacity=".35"/>'
            + mark(look.shape, 280, 230, 250, look.ink if contrast(look.ink, look.accent) >= 2 else look.paper,
                   look.second, readable_on(look.ink, look.paper), look.initial, look.display)
            + _lines(280, 470, headline, size, look.on_accent, look.display, 900, rtl=look.rtl, gap=1.12)
            + f'<rect y="700" width="560" height="92" fill="{look.ink}"/>'
            + _text(280, 742, look.name, 26, look.on_ink, look.display, 900, rtl=look.rtl)
            + (_text(280, 768, look.tagline, 14, look.on_ink, look.body, 400, rtl=look.rtl)
               if look.tagline else ""))
    return _svg(560, 792, body, "poster")


def website_svg(look: _Look) -> str:
    copy = look.copy
    headline = wrap(copy.get("site_headline") or look.tagline or look.name, 22, 2)
    sub = wrap(copy.get("site_sub") or "", 46, 2)
    services = [str(s)[:22] for s in (copy.get("services") or []) if s][:3]
    cta = str(copy.get("cta") or "")[:22]
    right, left = 880, 80
    logo_x, nav_anchor, nav_x = (right - 20, "start", left) if look.rtl else (left + 20, "end", right)
    text_x, anchor = (right, "end") if look.rtl else (left, "start")
    body = (f'<rect width="960" height="640" rx="14" fill="#D5D8DC"/>'
            f'<rect x="0" y="0" width="960" height="44" rx="14" fill="#ECEEF0"/>'
            f'<circle cx="26" cy="22" r="6" fill="#F26B5E"/><circle cx="46" cy="22" r="6" fill="#F5BF4F"/>'
            f'<circle cx="66" cy="22" r="6" fill="#61C554"/>'
            f'<rect x="200" y="10" width="560" height="24" rx="12" fill="#FFFFFF"/>'
            f'<rect x="8" y="44" width="944" height="588" fill="{look.paper}"/>'
            f'<rect x="8" y="44" width="944" height="64" fill="{look.paper}"/>'
            + look.mark(logo_x, 76, 36)
            + _text(logo_x + (-30 if look.rtl else 30), 83, look.name, 20, look.on_paper, look.display, 900,
                    "end" if look.rtl else "start", look.rtl)
            + "".join(f'<rect x="{(nav_x + i * 76) if look.rtl else (nav_x - 60 - i * 76)}" y="70" width="60" '
                      f'height="10" rx="5" fill="{look.on_paper}" opacity=".28"/>' for i in range(3))
            # hero
            + f'<rect x="8" y="108" width="944" height="300" fill="{look.ink}"/>'
            f'<circle cx="{180 if look.rtl else 780}" cy="258" r="118" fill="{look.accent}" opacity=".9"/>'
            + mark(look.shape, 180 if look.rtl else 780, 258, 130, look.second, look.paper,
                   readable_on(look.second, look.ink), look.initial, look.display)
            + _lines(text_x, 210, headline, 42, look.on_ink, look.display, 900, anchor, look.rtl, 1.2)
            + _lines(text_x, 220 + len(headline) * 50, sub, 17, look.on_ink, look.body, 400, anchor, look.rtl, 1.5))
    if cta:
        bx = right - 190 if look.rtl else left
        body += (f'<rect x="{bx}" y="338" width="190" height="46" rx="23" fill="{look.accent}"/>'
                 + _text(bx + 95, 367, cta, 17, look.on_accent, look.display, 700, rtl=look.rtl))
